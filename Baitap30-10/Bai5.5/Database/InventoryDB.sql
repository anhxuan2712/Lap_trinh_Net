CREATE DATABASE IF NOT EXISTS InventoryDB
	CHARACTER SET utf8mb4
	COLLATE utf8mb4_unicode_ci;

USE InventoryDB;

CREATE TABLE IF NOT EXISTS NhaCungCap (
	MaNCC INT NOT NULL AUTO_INCREMENT,
	TenNCC VARCHAR(150) NOT NULL,
	DienThoai VARCHAR(15) NULL,
	DiaChi VARCHAR(255) NULL,
	PRIMARY KEY (MaNCC),
	UNIQUE KEY uq_NhaCungCap_DienThoai (DienThoai)
) ENGINE = InnoDB;

CREATE TABLE IF NOT EXISTS VatTu (
	MaVatTu VARCHAR(20) NOT NULL,
	TenVatTu VARCHAR(150) NOT NULL,
	DVT VARCHAR(20) NULL,
	SoLuongTon DECIMAL(18, 2) NOT NULL DEFAULT 0,
	PRIMARY KEY (MaVatTu),
	CONSTRAINT chk_VatTu_SoLuongTon CHECK (SoLuongTon >= 0)
) ENGINE = InnoDB;

CREATE TABLE IF NOT EXISTS PhieuKho (
	MaPhieu INT NOT NULL AUTO_INCREMENT,
	LoaiPhieu VARCHAR(10) NOT NULL,
	NgayLap DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	MaNCC INT NULL,
	TongTien DECIMAL(18, 2) NOT NULL DEFAULT 0,
	PRIMARY KEY (MaPhieu),
	KEY ix_PhieuKho_MaNCC (MaNCC),
	CONSTRAINT chk_PhieuKho_LoaiPhieu CHECK (LoaiPhieu IN ('NHAP', 'XUAT')),
	CONSTRAINT fk_PhieuKho_NhaCungCap FOREIGN KEY (MaNCC)
		REFERENCES NhaCungCap (MaNCC)
		ON UPDATE CASCADE
		ON DELETE RESTRICT
) ENGINE = InnoDB;

CREATE TABLE IF NOT EXISTS ChiTietPhieuKho (
	MaPhieu INT NOT NULL,
	MaVatTu VARCHAR(20) NOT NULL,
	SoLuong DECIMAL(18, 2) NOT NULL,
	DonGia DECIMAL(18, 2) NOT NULL DEFAULT 0,
	PRIMARY KEY (MaPhieu, MaVatTu),
	KEY ix_ChiTietPhieuKho_MaVatTu (MaVatTu),
	CONSTRAINT chk_ChiTietPhieuKho_SoLuong CHECK (SoLuong > 0),
	CONSTRAINT chk_ChiTietPhieuKho_DonGia CHECK (DonGia >= 0),
	CONSTRAINT fk_ChiTietPhieuKho_PhieuKho FOREIGN KEY (MaPhieu)
		REFERENCES PhieuKho (MaPhieu)
		ON UPDATE CASCADE
		ON DELETE RESTRICT,
	CONSTRAINT fk_ChiTietPhieuKho_VatTu FOREIGN KEY (MaVatTu)
		REFERENCES VatTu (MaVatTu)
		ON UPDATE CASCADE
		ON DELETE RESTRICT
) ENGINE = InnoDB;