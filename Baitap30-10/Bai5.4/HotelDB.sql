CREATE DATABASE IF NOT EXISTS HotelDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE HotelDB;

CREATE TABLE IF NOT EXISTS Phong (
	SoPhong VARCHAR(10) PRIMARY KEY,
	LoaiPhong VARCHAR(50) NOT NULL,
	GiaTheoGio DECIMAL(18,2) NOT NULL,
	TrangThai VARCHAR(30) NOT NULL DEFAULT 'Trống'
);

CREATE TABLE IF NOT EXISTS KhachHang (
	MaKH INT PRIMARY KEY AUTO_INCREMENT,
	HoTen VARCHAR(100) NOT NULL,
	CCCD VARCHAR(20) NOT NULL UNIQUE,
	SoDienThoai VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS DichVu (
	MaDV INT PRIMARY KEY AUTO_INCREMENT,
	TenDV VARCHAR(100) NOT NULL,
	DonGia DECIMAL(18,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS PhieuDatPhong (
	MaPhieu INT PRIMARY KEY AUTO_INCREMENT,
	SoPhong VARCHAR(10) NOT NULL,
	MaKH INT NOT NULL,
	NgayNhanPhong DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	NgayTraPhong DATETIME NULL,
	TongTienThanhToan DECIMAL(18,2) NOT NULL DEFAULT 0,
	CONSTRAINT FK_Phieu_Phong FOREIGN KEY (SoPhong) REFERENCES Phong(SoPhong),
	CONSTRAINT FK_Phieu_Khach FOREIGN KEY (MaKH) REFERENCES KhachHang(MaKH)
);

CREATE TABLE IF NOT EXISTS SuDungDichVu (
	MaPhieu INT NOT NULL,
	MaDV INT NOT NULL,
	SoLuong INT NOT NULL,
	ThoiGian DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY (MaPhieu, MaDV, ThoiGian),
	CONSTRAINT FK_SuDung_Phieu FOREIGN KEY (MaPhieu) REFERENCES PhieuDatPhong(MaPhieu),
	CONSTRAINT FK_SuDung_DichVu FOREIGN KEY (MaDV) REFERENCES DichVu(MaDV)
);

