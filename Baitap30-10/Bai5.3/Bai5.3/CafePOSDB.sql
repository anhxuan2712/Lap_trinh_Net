CREATE DATABASE IF NOT EXISTS CafePOSDB CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE CafePOSDB;

CREATE TABLE IF NOT EXISTS BanAn (
	MaBan INT PRIMARY KEY AUTO_INCREMENT,
	TenBan NVARCHAR(50) NOT NULL,
	TrangThai NVARCHAR(20) NOT NULL DEFAULT 'Trống'
);
CREATE TABLE IF NOT EXISTS DanhMuc (
	MaDanhMuc INT PRIMARY KEY AUTO_INCREMENT,
	TenDanhMuc NVARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS MonAn (
	MaMon INT PRIMARY KEY AUTO_INCREMENT,
	TenMon NVARCHAR(100) NOT NULL,
	MaDanhMuc INT NOT NULL,
	DonGia DECIMAL(18,2) NOT NULL CHECK (DonGia >= 0),
	CONSTRAINT FK_MonAn_DanhMuc FOREIGN KEY (MaDanhMuc) REFERENCES DanhMuc(MaDanhMuc)
);
CREATE TABLE IF NOT EXISTS HoaDon (
	MaHoaDon INT PRIMARY KEY AUTO_INCREMENT,
	MaBan INT NOT NULL,
	GioVao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
	GioRa DATETIME NULL,
	TongTien DECIMAL(18,2) NOT NULL DEFAULT 0,
	TrangThai BIT NOT NULL DEFAULT 0,
	CONSTRAINT FK_HoaDon_BanAn FOREIGN KEY (MaBan) REFERENCES BanAn(MaBan)
);
CREATE TABLE IF NOT EXISTS ChiTietHoaDon (
	MaChiTiet INT PRIMARY KEY AUTO_INCREMENT,
	MaHoaDon INT NOT NULL,
	MaMon INT NOT NULL,
	SoLuong INT NOT NULL CHECK (SoLuong > 0),
	DonGia DECIMAL(18,2) NOT NULL CHECK (DonGia >= 0),
	CONSTRAINT FK_ChiTiet_HoaDon FOREIGN KEY (MaHoaDon) REFERENCES HoaDon(MaHoaDon),
	CONSTRAINT FK_ChiTiet_MonAn FOREIGN KEY (MaMon) REFERENCES MonAn(MaMon),
	CONSTRAINT UQ_ChiTiet_HoaDon_Mon UNIQUE (MaHoaDon, MaMon)
);

